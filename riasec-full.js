function showSection(sectionId) {
    window.scrollTo(0, 0);
    document.documentElement.scrollTop = 0;
    document.body.scrollTop = 0;

    document.querySelectorAll('.section').forEach(s => s.classList.remove('active'));
    document.getElementById(sectionId).classList.add('active');

    requestAnimationFrame(() => {
        window.scrollTo(0, 0);
        document.documentElement.scrollTop = 0;
        document.body.scrollTop = 0;
    });
}

function renderQuestion() {
    const question = questions[currentQuestionIndex];
    const container = document.getElementById('questionsContainer');

    const inputType = question.multiple ? 'checkbox' : 'radio';
    const inputName = `q${question.id}`;

    let html = `
        <div class="question-card">
            <h3 class="question-title">${question.text}</h3>
            <div class="options">
    `;

    question.options.forEach(option => {
        const checked = answers[question.id] &&
            (question.multiple ? answers[question.id].includes(option.value) : answers[question.id] === option.value);

        html += `
            <div class="option ${checked ? 'selected' : ''}" onclick="selectOption(this, ${question.id}, '${option.value}', ${question.multiple || false})">
                <input type="${inputType}"
                       name="${inputName}"
                       value="${option.value}"
                       ${checked ? 'checked' : ''}>
                <label>${option.text}</label>
            </div>
        `;
    });

    html += `
            </div>
        </div>
    `;

    container.innerHTML = html;

    updateProgress();
    updateButtons();
}

function selectOption(element, questionId, value, isMultiple) {
    if (isMultiple) {
        if (!answers[questionId]) answers[questionId] = [];

        const input = element.querySelector('input');
        const index = answers[questionId].indexOf(value);

        if (index > -1) {
            answers[questionId].splice(index, 1);
            element.classList.remove('selected');
            input.checked = false;
        } else {
            answers[questionId].push(value);
            element.classList.add('selected');
            input.checked = true;
        }
    } else {
        answers[questionId] = value;

        document.querySelectorAll('.option').forEach(opt => opt.classList.remove('selected'));
        element.classList.add('selected');
        element.querySelector('input').checked = true;
    }
}

function updateProgress() {
    const progress = ((currentQuestionIndex + 1) / questions.length) * 100;
    document.getElementById('progressBar').style.width = progress + '%';
    document.getElementById('currentQuestion').textContent = currentQuestionIndex + 1;
}

function updateButtons() {
    const prevBtn = document.getElementById('prevBtn');
    const nextBtn = document.getElementById('nextBtn');
    const submitBtn = document.getElementById('submitBtn');

    if (prevBtn) {
        prevBtn.style.display = 'block';
        prevBtn.style.visibility = currentQuestionIndex > 0 ? 'visible' : 'hidden';
    }

    if (nextBtn) {
        nextBtn.style.display = currentQuestionIndex < questions.length - 1 ? 'block' : 'none';
    }

    if (submitBtn) {
        submitBtn.style.display = currentQuestionIndex === questions.length - 1 ? 'block' : 'none';
    }
}

function nextQuestion() {
    if (currentQuestionIndex < questions.length - 1) {
        currentQuestionIndex++;
        renderQuestion();
    }
}

function prevQuestion() {
    if (currentQuestionIndex > 0) {
        currentQuestionIndex--;
        renderQuestion();
    }
}

function submitTest(e) {
    e.preventDefault();

    const t = translations[currentLanguage];

    // Validate all questions answered
    for (let i = 1; i <= questions.length; i++) {
        if (!answers[i] || (Array.isArray(answers[i]) && answers[i].length === 0)) {
            alert(t.allQuestionsRequired);
            return;
        }
    }

    const results = calculateRiasec();
    displayResults(results);
}

function calculateRiasec() {
    const scores = { R: 0, I: 0, A: 0, S: 0, E: 0, C: 0 };

    // Calculate scores from questions 1-50
    for (let i = 1; i <= 50; i++) {
        const answer = answers[i];
        const question = questions[i - 1];
        const option = question.options.find(opt => opt.value === answer);
        if (option) {
            scores[option.type]++;
        }
    }

    // Sort by score
    const sorted = Object.entries(scores).sort((a, b) => b[1] - a[1]);

    const top3 = sorted.slice(0, 3);
    const code = top3.map(([type]) => type).join('-');

    // Get majors from top 3 types
    const recommendedMajors = new Set();
    top3.forEach(([type]) => {
        majorsByType[type].slice(0, 4).forEach(major => recommendedMajors.add(major));
    });
    const majors = Array.from(recommendedMajors);

    // Get selected ENT subjects
    const selectedENT = answers[51] || [];
    const entTexts = selectedENT.map(value => {
        const option = questions[50].options.find(opt => opt.value === value);
        return option ? option.text : '';
    }).filter(t => t);

    return {
        code,
        scores,
        sorted,
        top3,
        majors,
        selectedENT: entTexts
    };
}

function displayResults(results) {
    window.scrollTo({ top: 0, left: 0, behavior: 'instant' });
    showSection('results-section');
    window.scrollTo({ top: 0, left: 0, behavior: 'instant' });

    const t = translations[currentLanguage];

    // Update UI text for results section
    document.getElementById('resultsTitle').textContent = t.resultsTitle;
    document.getElementById('yourTypeTitle').textContent = t.yourTypeTitle;
    document.getElementById('recommendedMajorsTitle').textContent = t.recommendedMajors;
    document.getElementById('entAnalysisTitle').textContent = t.entAnalysisTitle;
    document.getElementById('downloadPdfBtn').textContent = t.downloadPdf;

    // Display code
    document.getElementById('riasecCode').textContent = results.code;

    // Display description
    const descriptions = results.code.split('-').map(type => fullDescriptions[type]);
    document.getElementById('codeDescription').textContent = descriptions.join(' ');

    // Display scores chart
    const maxScore = results.sorted[0] ? results.sorted[0][1] : 50;
    const chartHTML = results.sorted
        .map(([type, score]) => `
            <div class="score-bar">
                <div class="score-label">
                    <span>${type} - ${typeDescriptions[type]}</span>
                    <span>${score}/50</span>
                </div>
                <div class="score-progress">
                    <div class="score-fill" style="width: ${(score / maxScore) * 100}%">
                        ${score}
                    </div>
                </div>
            </div>
        `).join('');

    document.getElementById('scoresChart').innerHTML = chartHTML;

    // Display majors
    const majorsHTML = results.majors.slice(0, 15).map(major =>
        `<span class="major-chip">${major}</span>`
    ).join('');

    document.getElementById('majorsList').innerHTML = majorsHTML;

    // ENT analysis
    const entTexts = results.selectedENT.map(ent => entAnalysisTexts[ent] || '').filter(t => t);
    const entAnalysis = entTexts.length > 0
        ? entTexts.join(' ')
        : (currentLanguage === 'kk' ? 'Профориентатормен таңдау пәндерін талқылауды ұсынамыз.' : 'Рекомендуем обсудить выбор профильных предметов с профориентатором.');

    document.getElementById('entAnalysis').textContent = entAnalysis;

    // Store results globally
    window.testResults = results;

    // Pre-generate PDF for instant download
    preGeneratePDF(results);

    setTimeout(() => {
        window.scrollTo(0, 0);
    }, 50);
}

// Pre-generate PDF in background for instant download
async function preGeneratePDF(results) {
    try {
        const response = await fetch('/generate-riasec-full-pdf', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json'
            },
            body: JSON.stringify({
                results: {
                    code: results.code,
                    scores: results.scores,
                    sorted: results.sorted,
                    top3: results.top3,
                    majors: results.majors,
                    selectedENT: results.selectedENT
                },
                studentInfo: studentInfo,
                language: currentLanguage
            })
        });

        if (!response.ok) {
            throw new Error('Server error');
        }

        const blob = await response.blob();

        // Clean up old PDF URL if exists
        if (preGeneratedPdfUrl) {
            URL.revokeObjectURL(preGeneratedPdfUrl);
        }

        // Store the pre-generated PDF
        preGeneratedPdfUrl = URL.createObjectURL(blob);
        const randomId = Math.random().toString(36).substring(2, 10);
        preGeneratedPdfFilename = `RIASEC_Full_${randomId}.pdf`;

        console.log('PDF pre-generated successfully');
    } catch (error) {
        console.error('Error pre-generating PDF:', error);
        // Don't show error to user, they can still generate on demand
    }
}

async function generatePDF() {
    const btn = document.getElementById('downloadPdfBtn');
    const t = translations[currentLanguage];
    const originalText = btn.textContent;

    // If PDF is pre-generated, download it instantly
    if (preGeneratedPdfUrl && preGeneratedPdfFilename) {
        const a = document.createElement('a');
        a.href = preGeneratedPdfUrl;
        a.download = preGeneratedPdfFilename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        return;
    }

    // Otherwise, generate on demand
    btn.textContent = t.pdfCreating;
    btn.disabled = true;

    try {
        const results = window.testResults;

        const response = await fetch('/generate-riasec-full-pdf', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json'
            },
            body: JSON.stringify({
                results: {
                    code: results.code,
                    scores: results.scores,
                    sorted: results.sorted,
                    top3: results.top3,
                    majors: results.majors,
                    selectedENT: results.selectedENT
                },
                studentInfo: studentInfo,
                language: currentLanguage
            })
        });

        if (!response.ok) {
            throw new Error('Server error');
        }

        const blob = await response.blob();
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        const randomId = Math.random().toString(36).substring(2, 10);
        a.download = `RIASEC_Full_${randomId}.pdf`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);

    } catch (error) {
        console.error('Error generating PDF:', error);
        alert(t.pdfError);
    } finally {
        btn.textContent = originalText;
        btn.disabled = false;
    }
}
